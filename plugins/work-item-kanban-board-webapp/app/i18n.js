// Resolved once: SystemLink reloads the page when the user changes language.
export const language = getSystemLinkLanguage();
const translations = TRANSLATIONS[language] ?? {};

if (globalThis.document?.documentElement) {
    document.documentElement.lang = language;
}

export function t(text, params) {
    const template = translations[text] ?? text;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}

// Translates static markup: [data-i18n] text and the attributes listed in [data-i18n-attrs].
export function translateDocument(root = document) {
    for (const element of root.querySelectorAll('[data-i18n]')) {
        const textNode = [...element.childNodes].find(node => node.nodeType === Node.TEXT_NODE && node.textContent.trim());
        if (textNode) {
            textNode.textContent = t(textNode.textContent.trim());
        }
    }
    for (const element of root.querySelectorAll('[data-i18n-attrs]')) {
        for (const name of element.dataset.i18nAttrs.split(/\s+/).filter(Boolean)) {
            const value = element.getAttribute(name);
            if (value) element.setAttribute(name, t(value));
        }
    }
}
